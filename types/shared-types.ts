/** A video's title, as `mux-asset`'s schema allows it. Checked before anything reaches Mux. */
export const MuxAssetTitle = z
  .string()
  .trim()
  .min(3, 'The title must be at least 3 characters long.')
  .max(255, 'The title must be at most 255 characters long.');

/**
 * Tags trimmed, without blanks, and without repeats that differ only in case. The first spelling stays.
 * Commas stay too: Robots writes tags like "$15,000". Only typing in the details form splits on them.
 */
export function normalizeTags(tags: string[]): string[] {
  const seen = new Set<string>();

  return tags
    .map((tag) => tag.trim())
    .filter((tag) => {
      const key = tag.toLowerCase();
      if (!tag || seen.has(key)) return false;
      seen.add(key);
      return true;
    });
}

/** .srt or .vtt file uploaded as subtitle/caption for a video */
export const TextTrackFile = z.object({
  contents: z.string(),
  type: z.string(),
  name: z.string(),
  size: z.number(),
});

/** Subtitles and captions uploaded by the user */
export const CustomTextTrack = z.object({
  file: TextTrackFile,
  name: z.string(),
  language_code: z.string(),
  closed_captions: z.boolean().default(false),
  stored_track: z.custom<Mux.Video.Track>((value) => typeof value === 'object' && value && 'id' in value).optional(),
});

export type ParsedCustomTextTrack = z.infer<typeof CustomTextTrack>;

export type StoredTextTrack = ParsedCustomTextTrack & { id: string; documentId: string };

export type StaticRenditionResolution = Mux.Video.Assets.AssetCreateStaticRenditionParams['resolution'];

/** In the order the upload form lists them. */
export const STATIC_RENDITION_RESOLUTIONS = [
  'audio-only',
  'highest',
  '2160p',
  '1440p',
  '1080p',
  '720p',
  '540p',
  '480p',
  '360p',
  '270p',
] as const satisfies readonly StaticRenditionResolution[];

/** Mux rejects `highest` alongside these. `audio-only` combines with anything. */
export const EXPLICIT_STATIC_RENDITION_RESOLUTIONS = STATIC_RENDITION_RESOLUTIONS.filter(
  (resolution) => resolution !== 'highest' && resolution !== 'audio-only'
);

export const DEFAULT_STATIC_RENDITIONS: StaticRenditionResolution[] = ['audio-only', '480p', '720p'];

/**
 * Captions Mux generates unless the uploader changes them. The same shape the upload form produces when
 * English is picked, so the track is named "English" either way.
 */
export const DEFAULT_AUTOGENERATED_CAPTIONS_LANGUAGES: { code: SupportedMuxLanguage; isSourceLanguage: boolean }[] = [
  { code: 'en', isSourceLanguage: false },
];

export const UploadConfig = z.object({
  /**
   * Downloadable MP4 (and M4A, for `audio-only`) files Mux creates alongside the stream. Replaces the
   * deprecated `mp4_support`, which Mux does not allow on the same asset. Mux skips any resolution
   * above the source's.
   * @see {@link https://www.mux.com/docs/guides/enable-static-mp4-renditions}
   * @defaultValue ['audio-only', '480p', '720p']
   */
  static_renditions: z
    .array(z.enum(STATIC_RENDITION_RESOLUTIONS))
    .refine(
      (resolutions) => new Set(resolutions).size === resolutions.length,
      'Each resolution can only be picked once'
    )
    .refine(
      (resolutions) =>
        !resolutions.includes('highest') ||
        !resolutions.some((resolution) => (EXPLICIT_STATIC_RENDITION_RESOLUTIONS as string[]).includes(resolution)),
      '"Highest" cannot be combined with a specific resolution'
    )
    .default(DEFAULT_STATIC_RENDITIONS),

  /**
   * Max resolution tier can be used to control the maximum resolution_tier your asset is encoded, stored, and streamed at.
   * @see {@link https://docs.mux.com/guides/stream-videos-in-4k}
   * @defaultValue '1080p'
   */
  max_resolution_tier: z.enum(['2160p', '1440p', '1080p']).default('1080p'),

  /**
   * The video quality informs the cost, quality, and available platform features for the asset.
   * @see {@link https://docs.mux.com/guides/use-video-quality-levels}
   * @defaultValue 'plus'
   */
  video_quality: z.enum(['basic', 'plus', 'premium']).default('plus'),

  /**
   * Whether or not to use signed URLs, making the asset private
   * @see {@link https://docs.mux.com/guides/use-encoding-tiers}
   * @defaultValue 'false'
   */
  signed: z.boolean().default(false),

  /**
   * Languages Mux auto-generates captions in. An empty list asks for none.
   * @defaultValue [{ code: 'en' }]
   */
  autogenerated_captions_languages: z
    .array(
      z.object({
        code: z.enum(SUPPORTED_MUX_LANGUAGES_VALUES as [SupportedMuxLanguage, ...SupportedMuxLanguage[]]),
        isSourceLanguage: z.boolean().default(false),
      })
    )
    .default(() => DEFAULT_AUTOGENERATED_CAPTIONS_LANGUAGES.map((language) => ({ ...language }))),

  custom_text_tracks: z.array(CustomTextTrack).optional(),

  upload_type: z.enum(['file', 'url']).default('file'),

  /**
   * The configured default Robots directives the person kept checked. Only someone with Run Robots
   * can narrow the list; the server ignores it for everyone else.
   */
  directives: z.array(z.string()).optional(),
});

export type RequestedUploadConfig = z.input<typeof UploadConfig>;
export type ParsedUploadConfig = z.infer<typeof UploadConfig>;

export const UploadData = z
  .object({ title: MuxAssetTitle })
  .and(
    z.discriminatedUnion('upload_type', [
      z.object({ upload_type: z.literal('file'), file: z.custom<File>((value) => value instanceof File) }),
      z.object({ upload_type: z.literal('url'), url: z.string().url() }),
    ])
  )
  .and(UploadConfig);

export type RequestedUploadData = z.input<typeof UploadData>;

/**
 * Used by `server/controllers/mux.ts` as that doesn't receive the file from the front-end.
 * Users upload the file directly from the browser via the presigned URL generated in `parseUploadRequest`.
 */
export const UploadDataWithoutFile = z
  .object({ title: MuxAssetTitle })
  .and(
    z.discriminatedUnion('upload_type', [
      z.object({ upload_type: z.literal('file') }),
      z.object({ upload_type: z.literal('url'), url: z.string().url() }),
    ])
  )
  .and(UploadConfig);

export function uploadConfigToNewAssetInput(
  config: ParsedUploadConfig,
  storedTextTracks: StoredTextTrack[] = [],
  url?: string
): Mux.Video.Assets.InputSettings[] | undefined {
  const inputs: Mux.Video.Assets.InputSettings[] = [];

  const base: Mux.Video.Assets.InputSettings = {};

  if (config.upload_type === 'url') {
    base.url = url;
  }

  if (config.autogenerated_captions_languages.length > 0) {
    base.generated_subtitles = config.autogenerated_captions_languages.map((language) => {
      const label = SUPPORTED_MUX_LANGUAGES.find((l) => l.code === language.code)?.label || language.code;
      return {
        language_code: language.code,
        name: language.isSourceLanguage ? `${label} (CC)` : label,
        type: 'text',
        text_type: 'subtitles',
        closed_captions: true,
      };
    });
  }

  if (Object.keys(base).length > 0) {
    inputs.push(base);
  }

  if (storedTextTracks.length > 0) {
    inputs.push(...storedTextTracks.map(storedTextTrackToMuxTrack));
  }

  return inputs.length > 0 ? inputs : undefined;
}
