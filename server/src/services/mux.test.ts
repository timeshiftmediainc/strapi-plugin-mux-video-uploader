import { beforeEach, describe, expect, it, vi } from 'vitest';

import { mux, resetMux } from '../../../test/mux';
import { installFakeStrapi } from '../../../test/strapi';
import { UploadConfig } from '../../../types/shared-types';
import pluginPkg from '../../../package.json';
import muxService from './mux';

vi.mock('@mux/ts', async () => ({ default: (await import('../../../test/mux')).MuxMock }));

const config = (overrides: Record<string, unknown> = {}) =>
  UploadConfig.parse({ autogenerated_captions_languages: [{ code: 'en', isSourceLanguage: true }], ...overrides });

beforeEach(() => {
  installFakeStrapi();
  resetMux();
  mux.client.video.uploads.create.mockResolvedValue({ id: 'upl_1', url: 'https://storage.example/upload' });
  mux.client.video.assets.create.mockResolvedValue({ id: 'ast_1' });
});

describe('Mux client', () => {
  it('is built so the SDK never repeats a request on its own', async () => {
    await muxService().getAssetById('ast_1');

    expect(mux.options).toHaveLength(1);
    expect(mux.options[0]).toMatchObject({
      tokenId: 'test-token-id',
      tokenSecret: 'test-token-secret',
      maxRetries: 0,
      defaultHeaders: { 'x-source-platform': `Strapi CMS | ${pluginPkg.version}` },
    });
  });
});

describe('uploads', () => {
  it('attaches Robots directives to both kinds of upload when there are any', async () => {
    const directives = [{ id: 'drv_a' }];

    await muxService().getDirectUploadUrl({ config: config(), storedTextTracks: [], directives });
    await muxService().createRemoteAsset({
      config: config({ upload_type: 'url' }),
      storedTextTracks: [],
      url: 'https://x/y.mp4',
      directives,
    });

    expect(mux.client.video.uploads.create.mock.calls[0][0].new_asset_settings.directives).toEqual(directives);
    expect(mux.client.video.assets.create.mock.calls[0][0].directives).toEqual(directives);
  });

  it('creates a direct upload with inputs and playback_policies', async () => {
    await muxService().getDirectUploadUrl({ config: config({ signed: true }), storedTextTracks: [] });

    const [request] = mux.client.video.uploads.create.mock.calls[0];
    expect(request.new_asset_settings).toMatchObject({
      inputs: [{ generated_subtitles: [expect.objectContaining({ language_code: 'en' })] }],
      playback_policies: ['signed'],
    });
    expect(request.new_asset_settings).not.toHaveProperty('input');
    expect(request.new_asset_settings).not.toHaveProperty('playback_policy');
    expect(request.new_asset_settings).not.toHaveProperty('directives');
  });

  it('creates an asset from a URL with inputs and playback_policies', async () => {
    await muxService().createRemoteAsset({
      config: config({ upload_type: 'url' }),
      storedTextTracks: [],
      url: 'https://videos.example/clip.mp4',
    });

    const [request] = mux.client.video.assets.create.mock.calls[0];
    expect(request).toMatchObject({
      inputs: [expect.objectContaining({ url: 'https://videos.example/clip.mp4' })],
      playback_policies: ['public'],
    });
    expect(request).not.toHaveProperty('input');
    expect(request).not.toHaveProperty('playback_policy');
    expect(request).not.toHaveProperty('directives');
  });
});

describe('static renditions', () => {
  it('defaults to audio-only, 480p and 720p, and never sends the deprecated mp4_support', async () => {
    await muxService().getDirectUploadUrl({ config: config(), storedTextTracks: [] });

    const [request] = mux.client.video.uploads.create.mock.calls[0];
    expect(request.new_asset_settings.static_renditions).toEqual([
      { resolution: 'audio-only' },
      { resolution: '480p' },
      { resolution: '720p' },
    ]);
    expect(request.new_asset_settings).not.toHaveProperty('mp4_support');
  });

  it('sends the picked resolutions on an asset created from a URL', async () => {
    await muxService().createRemoteAsset({
      config: config({ upload_type: 'url', static_renditions: ['highest'] }),
      storedTextTracks: [],
      url: 'https://videos.example/clip.mp4',
    });

    const [request] = mux.client.video.assets.create.mock.calls[0];
    expect(request.static_renditions).toEqual([{ resolution: 'highest' }]);
    expect(request).not.toHaveProperty('mp4_support');
  });

  it('leaves static_renditions out when none are picked', async () => {
    await muxService().getDirectUploadUrl({ config: config({ static_renditions: [] }), storedTextTracks: [] });
    await muxService().createRemoteAsset({
      config: config({ upload_type: 'url', static_renditions: [] }),
      storedTextTracks: [],
      url: 'https://videos.example/clip.mp4',
    });

    expect(mux.client.video.uploads.create.mock.calls[0][0].new_asset_settings).not.toHaveProperty('static_renditions');
    expect(mux.client.video.assets.create.mock.calls[0][0]).not.toHaveProperty('static_renditions');
  });

  it('rejects highest alongside a specific resolution, but allows audio-only with either', () => {
    expect(UploadConfig.safeParse({ static_renditions: ['highest', '720p'] }).success).toBe(false);
    expect(UploadConfig.safeParse({ static_renditions: ['720p', '720p'] }).success).toBe(false);
    expect(UploadConfig.safeParse({ static_renditions: ['1080p'] }).success).toBe(true);
    expect(UploadConfig.safeParse({ static_renditions: ['audio-only', 'highest'] }).success).toBe(true);
    expect(UploadConfig.safeParse({ static_renditions: ['audio-only', '1080p', '270p'] }).success).toBe(true);
    expect(UploadConfig.safeParse({ static_renditions: ['4k'] }).success).toBe(false);
  });
});

describe('upload defaults', () => {
  it('asks for plus video quality and English auto-generated captions when nothing is picked', async () => {
    await muxService().getDirectUploadUrl({ config: UploadConfig.parse({}), storedTextTracks: [] });
    await muxService().createRemoteAsset({
      config: UploadConfig.parse({ upload_type: 'url' }),
      storedTextTracks: [],
      url: 'https://videos.example/clip.mp4',
    });

    const englishCaptions = [
      { language_code: 'en', name: 'English', type: 'text', text_type: 'subtitles', closed_captions: true },
    ];
    const { new_asset_settings } = mux.client.video.uploads.create.mock.calls[0][0];
    expect(new_asset_settings.video_quality).toBe('plus');
    expect(new_asset_settings.inputs).toEqual([{ generated_subtitles: englishCaptions }]);

    const asset = mux.client.video.assets.create.mock.calls[0][0];
    expect(asset.video_quality).toBe('plus');
    expect(asset.inputs).toEqual([{ url: 'https://videos.example/clip.mp4', generated_subtitles: englishCaptions }]);
  });

  it('keeps a picked video quality and caption languages', async () => {
    await muxService().getDirectUploadUrl({
      config: UploadConfig.parse({ video_quality: 'basic', autogenerated_captions_languages: [{ code: 'es' }] }),
      storedTextTracks: [],
    });

    const { new_asset_settings } = mux.client.video.uploads.create.mock.calls[0][0];
    expect(new_asset_settings.video_quality).toBe('basic');
    expect(new_asset_settings.inputs).toEqual([
      { generated_subtitles: [expect.objectContaining({ language_code: 'es', name: 'Spanish' })] },
    ]);
  });

  it('asks for no captions when every language is removed', async () => {
    await muxService().getDirectUploadUrl({
      config: UploadConfig.parse({ autogenerated_captions_languages: [] }),
      storedTextTracks: [],
    });
    await muxService().createRemoteAsset({
      config: UploadConfig.parse({ upload_type: 'url', autogenerated_captions_languages: [] }),
      storedTextTracks: [],
      url: 'https://videos.example/clip.mp4',
    });

    expect(mux.client.video.uploads.create.mock.calls[0][0].new_asset_settings.inputs).toBeUndefined();
    expect(mux.client.video.assets.create.mock.calls[0][0].inputs).toEqual([
      { url: 'https://videos.example/clip.mp4' },
    ]);
  });

  it('gives every upload its own default caption list', () => {
    const first = UploadConfig.parse({});
    first.autogenerated_captions_languages.push({ code: 'fr', isSourceLanguage: false });

    expect(UploadConfig.parse({}).autogenerated_captions_languages).toEqual([{ code: 'en', isSourceLanguage: false }]);
  });
});
